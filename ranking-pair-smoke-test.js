const assert=require('assert');
const fs=require('fs');
const root=__dirname;
const app=fs.readFileSync(root+'/app.js','utf8');
const css=fs.readFileSync(root+'/style.css','utf8');
const schema=fs.readFileSync(root+'/deploy/perguntas-ranking-duas-respostas.sql','utf8');
const staffReport=fs.readFileSync(root+'/deploy/relatorios-tempo-real-cruzamentos.sql','utf8');
const clientReport=fs.readFileSync(root+'/deploy/relatorios-resultados-clientes.sql','utf8');
const html=fs.readFileSync(root+'/app.html','utf8');
function ok(condition,message){assert(condition,message);}

ok(app.includes("ranking:'Ranking de preferências'"), 'tipo ranking ausente');
ok(app.includes("pair:'Duas respostas'"), 'tipo duas respostas ausente');
ok(app.includes('Q_HAS_QUOTA_OPTS'), 'separação entre opções de cota e ranking ausente');
ok(app.includes('acollectRankingMove')&&app.includes('acollectRankingDrop'), 'ordenador de ranking na coleta ausente');
ok(app.includes('acollectPairFieldBody')&&app.includes('acollectSetPairField'), 'coleta de dois subcampos ausente');
ok(app.includes('field_id:fieldId'), 'respostas compostas não são segregadas por subcampo');
ok(app.includes('value_number:index+1'), 'posição do ranking não é persistida');
ok(app.includes("update({is_active:false})")&&app.includes('activeColumnAvailable'), 'perguntas removidas não são preservadas com segurança');
ok(!app.includes("from('survey_questions').delete().eq('survey_id',surveyId)"), 'sincronização ainda apaga perguntas históricas');
ok(app.includes('survey_question_fields(*')||app.includes('survey_question_fields'), 'leitura dos subcampos não existe');
ok(app.includes('reportsCrossQuestionsForSurvey')&&app.includes("q.type!=='pair'&&q.type!=='ranking'"), 'filtro de cruzamentos dos formatos compostos ausente');
ok(app.includes('Ranking e “Duas respostas” aparecem no resultado geral'), 'orientação do relatório ausente');
ok(schema.includes("type in ('single','multi','ranking','pair','scale','scale10','nps','open','number','date')"), 'constraint de tipos não foi ampliada');
ok(schema.includes('add column if not exists is_active boolean not null default true'), 'marcação ativa das perguntas ausente');
ok(schema.includes('create table if not exists public.survey_question_fields'), 'tabela de subcampos ausente');
ok(schema.includes('add column if not exists field_id uuid'), 'coluna field_id ausente');
ok(schema.includes('on delete set null'), 'field_id não preserva respostas ao remover um subcampo');
ok(schema.includes('is_active boolean not null default true'), 'schema não garante preservação de perguntas removidas');
ok(schema.includes('options_jsonb jsonb not null'), 'opções fechadas dos subcampos ausentes');
ok(schema.includes('survey_answer_distribution')&&schema.includes("q.type='ranking'"), 'distribuição individual não foi atualizada');
ok(staffReport.includes('a.field_id')&&staffReport.includes("q.type='ranking'"), 'RPC de staff não trata ranking/subcampos');
ok(clientReport.includes('a.field_id')&&clientReport.includes("q.type='ranking'"), 'RPC de cliente não trata ranking/subcampos');
ok(staffReport.includes("q.type not in ('open','ranking','pair')"), 'RPC de cruzamento staff não exclui formatos compostos');
ok(clientReport.includes("q.type not in ('open','ranking','pair')"), 'RPC de cruzamento cliente não exclui formatos compostos');
ok(css.includes('.collect-ranking-row')&&css.includes('.collect-pair-fields'), 'estilos da coleta ausentes');
ok(css.includes('.q-pair-field-editor')&&css.includes('.q-format-hint'), 'estilos do editor ausentes');
ok(html.includes('app.js?v=20260922224500')&&html.includes('style.css?v=20260922224500'), 'cache da nova versão não foi atualizado');
console.log('ranking-pair-smoke-test: PASS');
