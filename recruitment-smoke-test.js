const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const moduleSource=fs.readFileSync(path.join(root,'recruitment.js'),'utf8');
const migration=fs.readFileSync(path.join(root,'deploy','recrutamento.sql'),'utf8');
const publicPage=fs.readFileSync(path.join(root,'cadastro.html'),'utf8');
const html=fs.readFileSync(path.join(root,'app.html'),'utf8');

assert.match(app,/recruitment:\{ico:/,'navegação de recrutamento ausente');
assert.match(app,/recrutador:\['recruitment'\]/,'papel recrutador sem navegação individual');
assert.match(app,/recruiter_code/,'código de recrutador não carregado no perfil');
assert.match(app,/recruiter_capture_value/,'valor por captação não persistido no perfil');
assert.match(moduleSource,/ranking/i,'ranking não encontrado');
assert.match(moduleSource,/recruiterLink/,'link individual ausente');
assert.match(moduleSource,/recruiter-qr/,'QR Code por recrutador ausente');
assert.match(moduleSource,/recruitmentNotifySignup/,'notificação interna via WhatsApp ausente');
assert.match(moduleSource,/userSetTab\('recrutador'\);userOpen\('new'\)/,'botão Novo recrutador não abre o perfil correto');
assert.match(moduleSource,/recruiter_captures/,'consulta de captações ausente');
assert.match(moduleSource,/approved/,'contagem de aprovados não encontrada');
assert.doesNotMatch(moduleSource,/signups[^\n]*created_at/,'ranking usa created_at inexistente em signups');
assert.match(moduleSource,/sent_at/,'ranking não usa sent_at de signups');
assert.match(migration,/create table if not exists public\.recruiter_captures/,'tabela de captações ausente');
assert.match(migration,/create or replace function public\.submit_recruiter_signup/,'RPC de cadastro rastreável ausente');
assert.match(migration,/create or replace function public\.recruiter_public_info/,'RPC de validação do link ausente');
assert.match(migration,/create or replace function public\.recruiter_capture_sync/,'trigger de sincronização ausente');
assert.match(migration,/on conflict \(signup_id\)/,'migration não é idempotente por signup');
assert.match(migration,/grant execute on function public\.submit_recruiter_signup[\s\S]*to anon/,'RPC pública sem grant anon');
assert.match(migration,/status in \('pendente','a_receber','paga','cancelada'\)/,'status de captação incompletos');
assert.match(migration,/sent_at desc/,'índice não usa timestamp real de signups');
assert.match(publicPage,/recruiter_public_info/,'página pública não valida recrutador');
assert.match(publicPage,/submit_recruiter_signup/,'página pública não grava captação');
assert.match(publicPage,/get\('recrutador'\)/,'parâmetro do link de recrutador ausente');
assert.match(publicPage,/p_cidades_atuacao/,'cidades de atuação não enviadas');
assert.match(html,/recruitment\.js\?v=20260830310000/,'módulo não carregado com cache-busting');
assert.ok(fs.existsSync(path.join(root,'vendor','qrcode.min.js')),'QR Code local ausente');
console.log('recruitment-smoke-test: OK');
