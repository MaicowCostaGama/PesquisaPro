const assert=require('assert');
const fs=require('fs');
const root=__dirname;
const app=fs.readFileSync(root+'/app.js','utf8');
const css=fs.readFileSync(root+'/style.css','utf8');
const migration=fs.readFileSync(root+'/deploy/pesquisadores-escolaridade-filtros.sql','utf8');
const schema=fs.readFileSync(root+'/deploy/schema.sql','utf8');
const ok=(condition,message)=>assert.ok(condition,message);

ok(app.includes("const SCHOOLING_OPTIONS="),'opções de escolaridade não definidas');
ok(app.includes('researcherLocations(user)'),'normalização de cidade/estado não implementada');
ok(app.includes('researcherIsAvailable(user)'),'critério de disponibilidade não implementado');
ok(app.includes("USER_RESEARCHER_FILTERS={state:'',city:'',schooling:''}"),'filtros administrativos não inicializados');
ok(app.includes('userResearcherFiltersMarkup(usersInTab(\'pesq\'))'),'filtros não exibidos na aba de pesquisadores');
ok(app.includes('teamFiltersMarkup(pesqs,hasTarget)'),'filtros não exibidos na seleção de equipe');
ok(app.includes("teamSetFilter('schooling',this.value)"),'filtro de escolaridade da equipe ausente');
ok(app.includes("teamSetFilter('state',this.value)"),'filtro de estado da equipe ausente');
ok(app.includes("teamSetFilter('city',this.value)"),'filtro de cidade da equipe ausente');
ok(app.includes("id=\"team-available-count\""),'contador de disponíveis da equipe ausente');
ok(app.includes("data-available=\"${available?'1':'0'}\""),'marcação de disponibilidade das linhas ausente');
ok(app.includes('const podeConvidar=!on&&!pend&&!naoSelecionavel&&researcherIsAvailable(u);'),'convite não está restrito a pesquisadores disponíveis');
ok(app.includes("row.escolaridade=rec.escolaridade||null"),'escolaridade não é persistida no perfil');
ok(app.includes('select class="inp" id="u-escolaridade"'),'campo administrativo de escolaridade ausente');
ok(app.includes(".select('id,name,email,phone,role,status,cpf,cpf_cnpj,pf_pj,birth,escolaridade"), 'consulta de perfis não carrega escolaridade');
ok(migration.includes('add column if not exists escolaridade'),'migration não é aditiva para escolaridade');
ok(migration.includes('profiles_pesq_filters_idx'),'índice de filtros não criado');
ok(schema.includes('escolaridade text'),'schema base não prevê escolaridade');
ok(css.includes('.researcher-filter-panel')&&css.includes('.team-filter-panel'),'estilos responsivos dos filtros ausentes');
console.log('researcher-availability-filters-smoke-test: PASS');
