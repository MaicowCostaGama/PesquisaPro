const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=__dirname;
const html=fs.readFileSync(path.join(root,'cadastro.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app.html'),'utf8')+fs.readFileSync(path.join(root,'app.js'),'utf8');
const migration=fs.readFileSync(path.join(root,'deploy','cadastro-pesquisador-senha.sql'),'utf8');
assert(html.includes('id="password"')&&html.includes('autocomplete="new-password"'),'campo de senha do pesquisador ausente');
assert(html.includes('id="password-confirm"'),'confirmação de senha ausente');
assert(html.includes('password.length<8'),'validação de senha mínima ausente');
assert(html.includes('password!==passwordConfirm'),'validação de confirmação ausente');
assert(html.includes('sb.auth.signUp({email,password})'),'criação de acesso Auth no cadastro ausente');
assert(html.includes('p_auth_user_id:authUserId'),'UUID Auth não enviado ao cadastro');
assert(html.includes("await sb.auth.signOut()"),'sessão temporária não é encerrada após cadastro');
assert(!migration.includes('p_password'),'migration não deve receber senha');
assert(migration.includes('auth_user_id uuid references auth.users(id)'),'vínculo Auth não existe');
assert(migration.includes('from auth.users u'),'validação do usuário Auth ausente');
assert(migration.includes('create or replace function public.submit_recruiter_signup'),'RPC de senha ausente');
assert(migration.includes('drop function if exists public.submit_recruiter_signup(text,text,text,date,text,text,text,text,text,text,text[])'),'RPC antiga sem autenticação não é removida');
assert(migration.includes('p_auth_user_id uuid')&&!migration.includes('p_auth_user_id uuid default null'),'UUID Auth deve ser obrigatório na nova RPC');
assert(migration.includes('submit_recruiter_signup(text,uuid,text,text,date,text,text,text,text,text,text,text[],text,text)'),'assinatura corrigida da RPC não encontrada');
assert(app.includes('requestOwnPasswordReset'),'recuperação por e-mail ausente');
assert(app.includes('completePasswordReset'),'definição de nova senha ausente');
assert(app.includes('resetPasswordForEmail'),'reset oficial do Supabase ausente');
assert(app.includes("return origin+'/app.html?redefinir-senha=1'"),'redirecionamento canônico do recovery ausente');
assert(app.includes('exchangeCodeForSession'),'tratamento de código PKCE ausente');
assert(app.includes('setSession({access_token:accessToken,refresh_token:refreshToken})'),'tratamento do token recovery ausente');
assert(app.includes('passwordRecoveryLinkPresent'),'detecção robusta do link de recovery ausente');
assert(app.includes('minlength="8"'),'mínimo de senha no fluxo de recuperação ausente');
assert(fs.readFileSync(path.join(root,'app.html'),'utf8').includes('app.js?v=20260922211500'),'cache de recovery não atualizado');
console.log('researcher-password-smoke-test: PASS');
