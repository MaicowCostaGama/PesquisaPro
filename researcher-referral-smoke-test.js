const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const recruitment=fs.readFileSync(path.join(root,'recruitment.js'),'utf8');
const cadastro=fs.readFileSync(path.join(root,'cadastro.html'),'utf8');
const migration=fs.readFileSync(path.join(root,'deploy','indicacao-pesquisador.sql'),'utf8');
const html=fs.readFileSync(path.join(root,'app.html'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');

assert.match(app,/PAGES\[['"]researcher-profile['"]\]/,'perfil do pesquisador ausente');
assert.match(app,/researcherReferralsMarkup/,'área de indicações ausente no perfil');
assert.match(app,/createResearcherReferral/,'ação para criar indicação ausente');
assert.match(app,/create_researcher_referral/,'RPC de criação não chamada no perfil');
assert.match(app,/researcher_referral_public_info|cadastro\.html/,'link público da indicação ausente');
assert.match(app,/researcherReferralWhatsapp/,'envio de indicação por WhatsApp ausente');
assert.match(app,/mark_researcher_referral_sent/,'registro do envio do link ausente');
assert.match(recruitment,/researcher_referrals/,'Recrutamento não consulta indicações');
assert.match(recruitment,/referrer_name/,'Recrutamento não mostra quem indicou');
assert.match(recruitment,/referred_name/,'Recrutamento não mostra quem foi indicado');
assert.match(recruitment,/recruitmentNotifyReferral/,'ação de contato da indicação ausente');
assert.match(cadastro,/indicacao/,'parâmetro público de indicação ausente');
assert.match(cadastro,/researcher_referral_public_info/,'cadastro não valida link de indicação');
assert.match(cadastro,/submit_researcher_referral_signup/,'cadastro não grava indicação');
assert.match(cadastro,/referrer_name/,'cadastro não apresenta origem da indicação');
assert.match(migration,/create table if not exists public\.researcher_referrals/,'tabela de indicações ausente');
assert.match(migration,/referrer_id uuid references public\.profiles/,'referência ao pesquisador indicador ausente');
assert.match(migration,/referral_token text not null unique/,'token individual não é único');
assert.match(migration,/create or replace function public\.create_researcher_referral/,'RPC de criação ausente');
assert.match(migration,/p\.role = 'pesq'/,'RPC não restringe criação a pesquisador');
assert.match(migration,/p\.status = 'ativo'/,'RPC não exige pesquisador ativo');
assert.match(migration,/create or replace function public\.researcher_referral_public_info/,'RPC pública do link ausente');
assert.match(migration,/create or replace function public\.submit_researcher_referral_signup/,'RPC de cadastro indicado ausente');
assert.match(migration,/for update/,'link não é bloqueado durante o cadastro');
assert.match(migration,/researcher_referral_id/,'cadastro não fica vinculado à indicação');
assert.match(migration,/create or replace function public\.sync_researcher_referral_signup/,'sincronização de status ausente');
assert.match(migration,/using \(public\.is_staff\(\)\)/,'gestão não possui leitura protegida das indicações');
assert.match(migration,/using \(referrer_id = auth\.uid\(\)\)/,'pesquisador não está limitado às próprias indicações');
assert.match(migration,/grant execute on function public\.researcher_referral_public_info\(text\) to anon, authenticated/,'link público sem acesso anon');
assert.match(migration,/grant execute on function public\.submit_researcher_referral_signup\(/,'RPC de cadastro sem grant');
assert.doesNotMatch(migration,/drop table|delete from public\.(profiles|signups|researcher_referrals)/i,'migration contém exclusão destrutiva');
assert.match(html,/app\.js\?v=20261007182506/,'cache do app não atualizado');
